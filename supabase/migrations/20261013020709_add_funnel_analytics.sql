create table if not exists public.funnel_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in (
    'gig_viewed', 'checkout_started', 'offer_accepted', 'payment_completed',
    'delivery_submitted', 'revision_requested', 'order_completed', 'review_submitted'
  )),
  user_id uuid references public.profiles(id) on delete set null,
  visitor_id text,
  resource_id text,
  resource_type text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists funnel_events_name_created_idx
  on public.funnel_events (event_name, created_at desc);
create index if not exists funnel_events_user_created_idx
  on public.funnel_events (user_id, created_at desc)
  where user_id is not null;

alter table public.funnel_events enable row level security;
revoke all on table public.funnel_events from anon, authenticated;
grant select, insert on table public.funnel_events to service_role;
revoke all on sequence public.funnel_events_id_seq from anon, authenticated;
grant usage, select on sequence public.funnel_events_id_seq to service_role;
